const isGroup = (v) => v !== null && typeof v === 'object' && !Array.isArray(v);
const joined = (a, b) => Object.freeze(Object.fromEntries([...Object.keys(a), ...Object.keys(b).filter((k) => !(k in a))]
 .map((k) => [k, k in b ? (isGroup(a[k]) && isGroup(b[k]) ? joined(a[k], b[k]) : b[k]) : a[k]])));
export function mergeStrings(extra) {
 for (const [k, v] of Object.entries(extra)) STRINGS[k] = k in STRINGS && isGroup(STRINGS[k]) && isGroup(v) ? joined(STRINGS[k], v) : v;
 Object.freeze(STRINGS);
}
