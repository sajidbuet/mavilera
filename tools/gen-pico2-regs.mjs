// address of every peripheral block and, for the blocks the pico2 module models (MODELLED), each register's offset, reset value
// and field-class masks. Decided by the author on 2026-11-06 (research decision D13, Q1). Reads the SVD as text.
// Usage: node tools/gen-pico2-regs.mjs <path to RP2350.svd>
