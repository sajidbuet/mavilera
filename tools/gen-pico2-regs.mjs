import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const MODELLED = ['SYSINFO', 'SYSCFG', 'CLOCKS', 'PSM', 'RESETS', 'IO_BANK0', 'IO_QSPI', 'PADS_BANK0', 'PADS_QSPI', 'XOSC', 'PLL_SYS',
  'ACCESSCTRL', 'BUSCTRL', 'UART0', 'TIMER0', 'WATCHDOG', 'BOOTRAM', 'ROSC', 'POWMAN', 'TICKS', 'XIP_CTRL', 'QMI', 'SIO', 'USB',
  'PWM', 'DMA', // PWM and DMA: P1-M5 (research D39)
  'ADC', 'SPI0', 'I2C0', // P1-M7 (SPI1 and I2C1 derive from them)
  'PIO0']; // P1-M8 (PIO1 and PIO2 derive from it)
const SKIP_BLOCKS = new Set(['VIRTUAL', 'PPB', 'PPB_NS', 'EPPB', 'SIO_NS']); // Arm-only blocks; the SIO mirror is decoded by the bus

const svdPath = process.argv[2];
if (!svdPath) { console.error('usage: node tools/gen-pico2-regs.mjs <RP2350.svd>'); process.exit(2); }
const xml = fs.readFileSync(svdPath, 'utf8').replace(/\r\n/g, '\n'); // a CRLF checkout hashes and parses as the LF file
const tag = (s, t) => { const m = s.match(new RegExp(`<${t}>([^<]*)</${t}>`)); return m ? m[1].trim() : undefined; };

const blocks = [];
const regs = new Map();
for (const m of xml.matchAll(/<peripheral(?:\s+derivedFrom="([^"]+)")?>([\s\S]*?)<\/peripheral>/g)) {
  const body = m[2], head = body.split('<registers>')[0];
  const name = tag(head, 'name'), base = Number(tag(head, 'baseAddress'));
  if (SKIP_BLOCKS.has(name)) continue;
  blocks.push([name, base, m[1] ?? null]);
  if (m[1]) continue;
  const list = [];
  for (const r of body.matchAll(/<register>([\s\S]*?)<\/register>/g)) {
    const rb = r[1], rh = rb.split('<fields>')[0];
    let rw = 0, w1c = 0, ro = 0, wo = 0, rse = 0;
    for (const f of rb.matchAll(/<field>([\s\S]*?)<\/field>/g)) {
      const br = tag(f[1], 'bitRange').match(/\[(\d+):(\d+)\]/);
      const hi = Number(br[1]), lo = Number(br[2]);
      const mask = (hi - lo === 31 ? 0xffffffff : ((1 << (hi - lo + 1)) - 1) << lo) >>> 0;
      const access = tag(f[1], 'access'), mwv = tag(f[1], 'modifiedWriteValues');
      if (mwv === 'oneToClear') w1c |= mask;
      else if (access === 'read-write') rw |= mask;
      else if (access === 'read-only') ro |= mask;
      else if (access === 'write-only') wo |= mask;
      if (/<readAction>/.test(f[1])) rse |= mask;
    }
    list.push([tag(rh, 'name'), Number(tag(rh, 'addressOffset')), Number(tag(rh, 'resetValue') ?? 0) >>> 0, rw >>> 0, w1c >>> 0, ro >>> 0, wo >>> 0, rse >>> 0]);
  }
  regs.set(name, list);
}
blocks.sort((a, b) => a[1] - b[1]);
const hex = (v) => `0x${(v >>> 0).toString(16)}`;
const sha = crypto.createHash('sha256').update(xml).digest('hex');
let out = `// regs.generated.js -- GENERATED by tools/gen-pico2-regs.mjs; do not edit. Register data derived from RP2350.svd of pico-sdk 2.3.1
// (SHA-256 ${sha}), Copyright (c) 2024 Raspberry Pi Ltd., BSD-3-Clause (notice and licence text: THIRD_PARTY.md).
// SVD_BLOCKS: [name, base address, derivedFrom] of every block; SVD_REGS: for the modelled blocks, per register
// [name, offset, reset value, read-write mask, write-1-to-clear mask, read-only mask, write-only mask, read-side-effect mask].
// Copyright (c) 2026 Sajid Muhaimin Choudhury. Licensed under the Apache License, Version 2.0.
// Rights class: code.

export const SVD_BLOCKS = Object.freeze([
${blocks.map(([n, b, d]) => `  ['${n}', ${hex(b)}, ${d ? `'${d}'` : 'null'}],`).join('\n')}
]);

export const SVD_REGS = Object.freeze({
`;
for (const name of MODELLED) {
  const list = regs.get(name);
  if (!list) throw new Error(`block ${name} not in the SVD`);
  out += `  ${name}: [\n${list.map((r) => `    ['${r[0]}', ${hex(r[1])}, ${r.slice(2).map(hex).join(', ')}],`).join('\n')}\n  ],\n`;
}
out += '});\n';
const dest = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'src', 'arch', 'pico2', 'soc', 'regs.generated.js');
fs.mkdirSync(path.dirname(dest), { recursive: true });
fs.writeFileSync(dest, out);
console.log(`wrote ${dest}: ${blocks.length} blocks, ${MODELLED.length} modelled, ${(out.length / 1024).toFixed(1)} KiB`);
