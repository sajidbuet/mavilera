# build-llvm.ps1 -- step 2 of the Pico Full toolchain (pico2 P1-F2): host TableGen (MSYS2 g++, static) and clang + lld
# as one multi-call module for riscv32 only, built to wasm32-wasip1 with wasi-sdk 34 -> build\llvm.wasm.
# Options follow YoWASP clang's build.sh (reference) with: RISCV target only, default triple riscv32-unknown-elf,
# assertions OFF, MinSizeRel, ThinLTO, only clang and lld in the driver (experiment E-CC-WASM-1, R-CC-WASM-01 §3).
# Takes about an hour on the development host and much memory: close other programs first.
# Copyright (c) 2026 Sajid Muhaimin Choudhury. Licensed under the Apache License, Version 2.0.
. "$PSScriptRoot\env.ps1"
Need $LLVM_SRC 'llvm-project'; Need $WASI_SDK 'wasi-sdk'; Need $MSYS 'MSYS2 ucrt64'

# host tblgen: static, so another libstdc++ on PATH cannot break it (STATUS_ENTRYPOINT_NOT_FOUND, E-CC-WASM-1)
$tg = Join-Path $B 'tblgen'
$env:PATH = "$MSYS;$env:PATH"
cmake -G Ninja -S "$LLVM_SRC\llvm" -B $tg `
  -DCMAKE_BUILD_TYPE=Release -DCMAKE_C_COMPILER=gcc -DCMAKE_CXX_COMPILER=g++ -DCMAKE_EXE_LINKER_FLAGS=-static `
  -DLLVM_ENABLE_PROJECTS=clang -DLLVM_TARGETS_TO_BUILD=RISCV `
  -DLLVM_BUILD_TOOLS=OFF -DLLVM_INCLUDE_UTILS=OFF -DLLVM_INCLUDE_RUNTIMES=OFF `
  -DLLVM_INCLUDE_EXAMPLES=OFF -DLLVM_INCLUDE_TESTS=OFF -DLLVM_INCLUDE_BENCHMARKS=OFF -DLLVM_INCLUDE_DOCS=OFF `
  -DCLANG_BUILD_TOOLS=OFF -DCLANG_INCLUDE_TESTS=OFF -DCLANG_BUILD_EXAMPLES=OFF -DCLANG_INCLUDE_DOCS=OFF `
  -DLLVM_ENABLE_ZLIB=OFF -DLLVM_ENABLE_ZSTD=OFF -DLLVM_ENABLE_LIBXML2=OFF -DLLVM_ENABLE_TERMINFO=OFF
if ($LASTEXITCODE) { throw 'tblgen configure failed' }
cmake --build $tg --target llvm-tblgen clang-tblgen llvm-min-tblgen
if ($LASTEXITCODE) { throw 'tblgen build failed' }
$env:PATH = $env:PATH.Replace("$MSYS;", '') + ";$MSYS"   # run-time DLLs only, appended (no shadowing)

$cw = Join-Path $B 'clang-wasm'
$off = @('BUGPOINT','BUGPOINT_PASSES','DSYMUTIL','DXIL_DIS','GOLD','LLC','LLI','LLVM_AR','LLVM_AS','LLVM_BCANALYZER',
  'LLVM_CAT','LLVM_CFI_VERIFY','LLVM_CONFIG','LLVM_COV','LLVM_CVTRES','LLVM_CXXDUMP','LLVM_CXXFILT','LLVM_CXXMAP',
  'LLVM_C_TEST','LLVM_DEBUGINFOD','LLVM_DEBUGINFOD_FIND','LLVM_DEBUGINFO_ANALYZER','LLVM_DIFF','LLVM_DIS',
  'LLVM_DWARFDUMP','LLVM_DWARFUTIL','LLVM_DWP','LLVM_EXEGESIS','LLVM_EXTRACT','LLVM_GSYMUTIL','LLVM_IFS',
  'LLVM_JITLINK','LLVM_JITLISTENER','LLVM_LIBTOOL_DARWIN','LLVM_LINK','LLVM_LIPO','LLVM_LTO2','LLVM_LTO','LLVM_MCA',
  'LLVM_MC','LLVM_ML','LLVM_MODEXTRACT','LLVM_MT','LLVM_NM','LLVM_OBJCOPY','LLVM_OBJDUMP','LLVM_OPT_REPORT',
  'LLVM_PDBUTIL','LLVM_PROFDATA','LLVM_PROFGEN','LLVM_RC','LLVM_READOBJ','LLVM_READTAPI','LLVM_REDUCE',
  'LLVM_REMARKUTIL','LLVM_RTDYLD','LLVM_SHLIB','LLVM_SIM','LLVM_SIZE','LLVM_SPLIT','LLVM_STRESS','LLVM_STRINGS',
  'LLVM_SYMBOLIZER','LLVM_TLI_CHECKER','LLVM_UNDNAME','LLVM_XRAY','LTO','OBJ2YAML','OPT','OPT_VIEWER',
  'REDUCE_CHUNK_LIST','REMARKS_SHLIB','SANCOV','SANSTATS','SPIRV_TOOLS','VERIFY_USELISTORDER','XCODE_TOOLCHAIN',
  'YAML2OBJ','LLVM_OFFLOAD_BINARY','LLVM_OFFLOAD_WRAPPER','LLVM_IR2VEC','LLVM_CGDATA','LLVM_CTXPROF_UTIL') |
  ForEach-Object { "-DLLVM_TOOL_${_}_BUILD=OFF" }
cmake -G Ninja -S "$LLVM_SRC\llvm" -B $cw `
  "-DCMAKE_TOOLCHAIN_FILE=$PF\cmake\Toolchain-WASI-LLVM.cmake" "-DLLVM_NATIVE_TOOL_DIR=$tg\bin" `
  -DCMAKE_BUILD_TYPE=MinSizeRel -DLLVM_ENABLE_ASSERTIONS=OFF `
  -DLLVM_BUILD_SHARED_LIBS=OFF -DLLVM_ENABLE_PIC=OFF -DLLVM_BUILD_STATIC=ON -DLLVM_ENABLE_THREADS=OFF `
  -DLLVM_BUILD_RUNTIME=OFF -DLLVM_BUILD_TOOLS=OFF -DLLVM_INCLUDE_UTILS=OFF -DLLVM_BUILD_UTILS=OFF `
  -DLLVM_INCLUDE_RUNTIMES=OFF -DLLVM_INCLUDE_EXAMPLES=OFF -DLLVM_INCLUDE_TESTS=OFF -DLLVM_INCLUDE_BENCHMARKS=OFF `
  -DLLVM_INCLUDE_DOCS=OFF -DLLVM_ENABLE_ZLIB=OFF -DLLVM_ENABLE_ZSTD=OFF -DLLVM_ENABLE_LIBXML2=OFF -DLLVM_ENABLE_TERMINFO=OFF `
  -DLLVM_TARGETS_TO_BUILD=RISCV -DLLVM_DEFAULT_TARGET_TRIPLE=riscv32-unknown-elf -DLLVM_HOST_TRIPLE=wasm32-unknown-wasip1 `
  -DLLVM_TOOL_LLVM_DRIVER_BUILD=ON -DHAVE_DLOPEN=0 -DHAVE_DLFCN_H=0 -DLLVM_ENABLE_PLUGINS=OFF `
  @off `
  -DLLVM_ENABLE_PROJECTS="clang;lld" `
  -DCLANG_ENABLE_ARCMT=OFF -DCLANG_ENABLE_STATIC_ANALYZER=OFF -DCLANG_INCLUDE_TESTS=OFF -DCLANG_BUILD_TOOLS=OFF `
  -DCLANG_TOOL_CLANG_SCAN_DEPS_BUILD=OFF -DCLANG_TOOL_CLANG_INSTALLAPI_BUILD=OFF -DCLANG_BUILD_EXAMPLES=OFF `
  -DCLANG_INCLUDE_DOCS=OFF -DCLANG_PLUGIN_SUPPORT=OFF -DCLANG_LINKS_TO_CREATE="clang;clang++" -DLLD_BUILD_TOOLS=OFF
if ($LASTEXITCODE) { throw 'clang-wasm configure failed' }
cmake --build $cw --target llvm-driver clang-resource-headers
if ($LASTEXITCODE) { throw 'clang-wasm build failed' }
Copy-Item (Join-Path $cw 'bin\llvm') $LLVM_WASM -Force
$h = (Get-FileHash $LLVM_WASM -Algorithm SHA256).Hash.ToLower()
"llvm.wasm: $((Get-Item $LLVM_WASM).Length) bytes, sha256 $h (pins.json outputs.llvmWasm: $($PINS.outputs.llvmWasm.sha256))"
